function tau = MPC_Controller_Casadi(x0,param)

import casadi.*

persistent solver U_prev

Np = param.Np;
dt = param.dt;

tau_max = param.tau_max(:);
%%--------------------------------------------------------
% Build CasADi solver only once
%%--------------------------------------------------------

if isempty(solver)

    solver = BuildSolver(param);

end

%%--------------------------------------------------------
% Warm start
%%--------------------------------------------------------

if isempty(U_prev)

    U0 = zeros(3*Np,1);

else

    U0 = [U_prev(4:end);
          U_prev(end-2:end)];

end

%%--------------------------------------------------------
% Bounds
%%--------------------------------------------------------

LB = repmat(-tau_max,Np,1);
UB = repmat( tau_max,Np,1);

%%--------------------------------------------------------
% Parameters
%%--------------------------------------------------------

P = [x0;
     param.xref];


%%--------------------------------------------------------
% Solve NLP
%%--------------------------------------------------------

sol = solver(...
        'x0',U0,...
        'lbx',LB,...
        'ubx',UB,...
        'p',P);

%%--------------------------------------------------------
% Optimal sequence
%%--------------------------------------------------------

U = full(sol.x);

%%--------------------------------------------------------
% Save warm start
%%--------------------------------------------------------

U_prev = U;

%%--------------------------------------------------------
% First control
%%--------------------------------------------------------

tau = U(1:3);

end