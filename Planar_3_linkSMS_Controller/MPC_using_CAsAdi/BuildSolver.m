function solver = BuildSolver(param)

import casadi.*

%% --------------------------------------------------------
% Parameters
%% --------------------------------------------------------

nx = 18;                 % [q;qdot]
nu = 3;                 % torques

Np = param.Np;
dt = param.dt;

Q = param.Q;
R = param.R;

%% --------------------------------------------------------
% Decision variables
%% --------------------------------------------------------

U = MX.sym('U',nu,Np);

%% --------------------------------------------------------
% Parameters passed online
%% --------------------------------------------------------

X0   = MX.sym('X0',nx);
XREF = MX.sym('XREF',nx);

P = [X0;
     XREF];

%% --------------------------------------------------------
% Initial state
%% --------------------------------------------------------

x = X0;

%% --------------------------------------------------------
% Cost
%% --------------------------------------------------------

J = 0;
f = SMS_Model_Casadi();

for k = 1:Np

    tau = U(:,k);

    % Propagate dynamics

    % x = rk4t_Casadi(@SMS_Model_Casadi,...
    %                 x,...
    %                 tau,...
    %                 dt);


    %% Build CasADi dynamics once

    x = rk4t_Casadi(f,...
                x,...
                tau,...
                dt);
    % Tracking error

    e = x - XREF;

    % Running cost

    J = J + e'*Q*e + tau'*R*tau;

end

%% --------------------------------------------------------
% Optimization variables
%% --------------------------------------------------------

OPT = reshape(U,nu*Np,1);

%% --------------------------------------------------------
% NLP
%% --------------------------------------------------------

nlp = struct(...
        'x',OPT,...
        'f',J,...
        'p',P);

%% --------------------------------------------------------
% IPOPT options
%% --------------------------------------------------------

opts = struct;

opts.ipopt.print_level = 0;
opts.print_time = 0;

opts.ipopt.max_iter = 20;%100

opts.ipopt.tol = 1e-3; %1e-4

%% --------------------------------------------------------
% Build solver
%% --------------------------------------------------------

solver = nlpsol(...
            'solver',...
            'ipopt',...
            nlp,...
            opts);

end