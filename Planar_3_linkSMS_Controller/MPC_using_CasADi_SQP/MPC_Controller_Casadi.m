function tau = MPC_Controller_Casadi(x,param)

persistent solver
persistent U_prev

%% ---------------------------------------------------------
% Build solver only once
%% ---------------------------------------------------------

if isempty(solver)
    solver = BuildSolver(param);
end

%% ---------------------------------------------------------
% Dimensions
%% ---------------------------------------------------------

Np = param.Np;
nu = 3;

%% ---------------------------------------------------------
% Initial guess
%% ---------------------------------------------------------

if isempty(U_prev)

    U0 = zeros(nu*Np,1);

else

    % Shift previous optimal sequence
    U0 = [U_prev(nu+1:end);
          U_prev(end-nu+1:end)];

end

%% ---------------------------------------------------------
% Torque bounds
%% ---------------------------------------------------------

tau_max = param.tau_max(:);

LB = repmat(-tau_max,Np,1);
UB = repmat( tau_max,Np,1);

%% ---------------------------------------------------------
% Solver parameters
%% ---------------------------------------------------------

P = [x;
     param.xref];

%% ---------------------------------------------------------
% Solve
%% ---------------------------------------------------------

% sol = solver( ...
%     'x0',  U0, ...
%     'lbx', LB, ...
%     'ubx', UB, ...
%     'p',   P);

cmd = ['sol = solver(', ...
       '''x0'',U0,', ...
       '''lbx'',LB,', ...
       '''ubx'',UB,', ...
       '''p'',P);'];

evalc(cmd);
%% ---------------------------------------------------------
% Extract optimal control sequence
%% ---------------------------------------------------------

U_prev = full(sol.x);

%% ---------------------------------------------------------
% Receding horizon control
%% ---------------------------------------------------------

tau = U_prev(1:nu);

end